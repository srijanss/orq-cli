use orq_core::review_input::InputError;
use orq_core::review_report::{build_report, render_markdown, ReportFile, ReportInputs};
use orq_core::review_summary::{apply_model_summary, SummaryConfig};

fn report() -> serde_json::Value {
    build_report(&ReportInputs {
        run_id: "run-1".into(),
        project_id: "p".into(),
        feature_id: "F".into(),
        base_sha: "0".repeat(40),
        head_sha: "1".repeat(40),
        files: vec![ReportFile { path: "src/a.rs".into(), old_path: None, added: Some(1), deleted: Some(0) }],
        tests: Err(InputError::Missing),
        review: Err(InputError::Missing),
        generated_at: "2026-01-01T00:00:00Z".into(),
    })
}

#[test]
fn the_summary_is_off_unless_the_config_enables_it_with_a_model() {
    assert_eq!(SummaryConfig::parse("").unwrap(), None);
    assert_eq!(SummaryConfig::parse("[review_summary]\nmodel = \"haiku\"\n").unwrap(), None);
    assert_eq!(SummaryConfig::parse("[review_summary]\nenabled = false\nmodel = \"haiku\"\n").unwrap(), None);
    assert_eq!(SummaryConfig::parse("[review_summary]\nenabled = true\nmodel = \"haiku\"\n").unwrap().unwrap().model, "haiku");
    assert!(SummaryConfig::parse("[review_summary]\nenabled = true\n").is_err());
    assert!(SummaryConfig::parse("[review_summary]\nenabled = true\nmodel = \"--dangerous flag\"\n").is_err());
    assert!(SummaryConfig::parse("[review_summary]\nenabled = \"yes\"\nmodel = \"haiku\"\n").is_err());
}

#[test]
fn a_generated_summary_is_labelled_grounded_in_the_report_and_shown_in_the_markdown() {
    let mut value = report();
    let seen = std::cell::RefCell::new(String::new());
    let run = |input: &str| {
        *seen.borrow_mut() = input.to_string();
        Ok("The change touches one source file.".to_string())
    };

    assert!(apply_model_summary(&mut value, "haiku", &run));

    assert!(seen.borrow().contains("src/a.rs"), "the model is given the report's evidence");
    assert_eq!(value["generated_summary"]["generated"], true);
    assert_eq!(value["generated_summary"]["model"], "haiku");
    assert_eq!(value["generated_summary"]["text"], "The change touches one source file.");
    let md = render_markdown(&value);
    assert!(md.contains("Summary (generated by haiku)") && md.contains("The change touches one source file."), "{md}");
}

#[test]
fn a_failed_or_empty_model_run_leaves_the_report_exactly_as_it_was() {
    let before = report();
    for run in [
        (&|_: &str| Err("model unavailable".to_string())) as &dyn Fn(&str) -> Result<String, String>,
        &|_: &str| Ok("  \n\t ".to_string()),
    ] {
        let mut value = before.clone();
        assert!(!apply_model_summary(&mut value, "haiku", run));
        assert_eq!(value, before);
    }
}

#[test]
fn generated_text_is_one_bounded_line_without_control_characters() {
    let mut value = report();
    let long = format!("first\u{1b}[31m line\n- forged\n{}", "x".repeat(5000));
    assert!(apply_model_summary(&mut value, "haiku", &|_| Ok(long.clone())));
    let text = value["generated_summary"]["text"].as_str().unwrap();
    assert!(!text.chars().any(char::is_control), "{text:?}");
    assert!(text.chars().count() <= 1500);
    assert!(text.starts_with("first"));
}
